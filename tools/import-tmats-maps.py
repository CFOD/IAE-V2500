"""Converts the component maps of NASA T-MATS' JT9D example into src/sim/maps/jt9d.js.

Source: https://github.com/nasa/T-MATS  (Trunk/TMATS_Examples/Example_JT9D/Simsetup/setup_*.m)
Licence: Apache 2.0, (c) United States Government as represented by the Administrator of NASA.
Run:  python3 tools/import-tmats-maps.py <path to T-MATS checkout>
"""
import re, sys, json, os
root = sys.argv[1] if len(sys.argv) > 1 else '/home/user/nasa/t-mats'
src = os.path.join(root, 'Trunk/TMATS_Examples/Example_JT9D/Simsetup')
out = {'source': 'NASA T-MATS, Example_JT9D (Apache License 2.0)', 'url': 'https://github.com/nasa/T-MATS'}
for comp in ['Fan', 'LPC', 'HPC', 'HPT', 'LPT']:
    text = open(os.path.join(src, f'setup_{comp}.m')).read()
    text = re.sub(r'%[^\n]*', '', text).replace('...', ' ')
    d = {}
    for name, body in re.findall(r'MWS\.%s\.(\w+)\s*=\s*\[(.*?)\]\s*;' % comp, text, re.S | re.I):
        rows = [[float(v) for v in r.replace(',', ' ').split()] for r in body.split(';') if r.strip()]
        d[name] = rows[0] if len(rows) == 1 else rows
    for name, val in re.findall(r'MWS\.%s\.(\w+)\s*=\s*([-+0-9.eE /]+?)\s*;' % comp, text, re.I):
        parts = [float(x) for x in val.split('/')]
        if name not in d: d[name] = parts[0] / parts[1] if len(parts) == 2 else parts[0]
    # some tables are written without row separators: reshape them to (speeds x second axis)
    n_nc = len(d['NcVec']); n_2 = len(d.get('RlineVec') or d.get('PRVec'))
    for k in ('WcArray', 'EffArray', 'PRArray'):
        v = d.get(k)
        if v and not isinstance(v[0], list):
            assert len(v) == n_nc * n_2, (comp, k, len(v)); d[k] = [v[i * n_2:(i + 1) * n_2] for i in range(n_nc)]
        if v: assert len(d[k]) == n_nc and all(len(r) == n_2 for r in d[k]), (comp, k)
    out[comp] = d
    print(comp, {k: (f'{len(v)}x{len(v[0])}' if isinstance(v, list) and isinstance(v[0], list) else (len(v) if isinstance(v, list) else v)) for k, v in d.items()})
HEAD = ("// Component maps of the JT9D reference model from NASA T-MATS (Example_JT9D).\n"
        "// Copyright United States Government as represented by the Administrator of NASA.\n"
        "// Licensed under the Apache License, Version 2.0: https://github.com/nasa/T-MATS\n"
        "// Generated by tools/import-tmats-maps.py - do not edit.\n")
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'sim', 'maps', 'jt9d.js'), 'w').write(HEAD + 'export default ' + json.dumps(out) + ';\n')
